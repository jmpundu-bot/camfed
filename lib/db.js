const { neon } = require('@neondatabase/serverless');

let sql;

function getSql() {
  const connectionString = process.env.DATABASE_URL?.trim();
  if (!connectionString) throw new Error('DATABASE_URL is not configured.');
  if (!sql) sql = neon(connectionString);
  return sql;
}

function numberIds(row) {
  if (!row) return row;
  if (row.id !== undefined) row.id = Number(row.id);
  if (row.event_id !== undefined) row.event_id = Number(row.event_id);
  return row;
}

async function initializeDatabase(legacyData = { events: [], attendees: [] }) {
  const query = getSql();
  await query`CREATE TABLE IF NOT EXISTS camfed_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    event_date TEXT NOT NULL,
    venue TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    created_at TEXT NOT NULL,
    registration_hours INTEGER NOT NULL DEFAULT 2,
    registration_expires_at TEXT NOT NULL,
    province TEXT NOT NULL DEFAULT 'Lusaka'
  )`;
  // Existing events belong to Lusaka until an administrator explicitly moves them.
  await query`ALTER TABLE camfed_events ADD COLUMN IF NOT EXISTS province TEXT NOT NULL DEFAULT 'Lusaka'`;
  await query`CREATE TABLE IF NOT EXISTS camfed_attendees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    gender TEXT NOT NULL,
    designation TEXT NOT NULL,
    organisation TEXT NOT NULL,
    phone_number TEXT NOT NULL,
    nrc_number TEXT NOT NULL,
    district TEXT NOT NULL,
    mobile_registered_name TEXT NOT NULL,
    signature_file TEXT,
    photo_file TEXT,
    event_id BIGINT NOT NULL REFERENCES camfed_events(id) ON DELETE CASCADE,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    gps_accuracy_m DOUBLE PRECISION,
    gps_captured_at TEXT,
    confirmation_token TEXT NOT NULL UNIQUE,
    created_at TEXT NOT NULL
  )`;
  await query`CREATE TABLE IF NOT EXISTS camfed_provincial_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_salt TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    province TEXT NOT NULL,
    created_at TEXT NOT NULL
  )`;
  await query`CREATE UNIQUE INDEX IF NOT EXISTS camfed_provincial_users_username_ci ON camfed_provincial_users (lower(username))`;
  await query`CREATE TABLE IF NOT EXISTS camfed_admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    password_salt TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TEXT NOT NULL
  )`;
  await query`CREATE UNIQUE INDEX IF NOT EXISTS camfed_admin_users_username_ci ON camfed_admin_users (lower(username))`;
  await query`CREATE UNIQUE INDEX IF NOT EXISTS camfed_attendees_phone_unique ON camfed_attendees (event_id, phone_number)`;
  await query`CREATE UNIQUE INDEX IF NOT EXISTS camfed_attendees_nrc_unique ON camfed_attendees (event_id, lower(nrc_number))`;
  await query`CREATE INDEX IF NOT EXISTS camfed_attendees_event_idx ON camfed_attendees (event_id, id)`;

  const counts = await query`SELECT
    (SELECT count(*) FROM camfed_events) AS event_count,
    (SELECT count(*) FROM camfed_attendees) AS attendee_count`;
  if (Number(counts[0].event_count) === 0 && Number(counts[0].attendee_count) === 0) {
    for (const event of legacyData.events || []) {
      await query`INSERT INTO camfed_events
        (id, name, event_date, venue, slug, created_at, registration_hours, registration_expires_at)
        VALUES (${event.id}, ${event.name}, ${event.date}, ${event.venue}, ${event.slug}, ${event.created_at || new Date().toISOString()}, ${event.registration_hours || 2}, ${event.registration_expires_at || new Date(Date.now() + 2 * 60 * 60 * 1000).toISOString()})
        ON CONFLICT (id) DO NOTHING`;
    }
    for (const attendee of legacyData.attendees || []) {
      await query`INSERT INTO camfed_attendees
        (id, full_name, gender, designation, organisation, phone_number, nrc_number, district, mobile_registered_name, signature_file, photo_file, event_id, latitude, longitude, gps_accuracy_m, gps_captured_at, confirmation_token, created_at)
        VALUES (${attendee.id}, ${attendee.full_name}, ${attendee.gender}, ${attendee.designation}, ${attendee.organisation}, ${attendee.phone_number}, ${attendee.nrc_number}, ${attendee.district}, ${attendee.mobile_registered_name}, ${attendee.signature_file || null}, ${attendee.photo_file || null}, ${attendee.event_id}, ${attendee.latitude ?? null}, ${attendee.longitude ?? null}, ${attendee.gps_accuracy_m ?? null}, ${attendee.gps_captured_at || null}, ${attendee.confirmation_token}, ${attendee.created_at || new Date().toISOString()})
        ON CONFLICT (id) DO NOTHING`;
    }
    await query`SELECT setval(pg_get_serial_sequence('camfed_events', 'id'), GREATEST(COALESCE((SELECT max(id) FROM camfed_events), 1), 1), EXISTS(SELECT 1 FROM camfed_events))`;
    await query`SELECT setval(pg_get_serial_sequence('camfed_attendees', 'id'), GREATEST(COALESCE((SELECT max(id) FROM camfed_attendees), 1), 1), EXISTS(SELECT 1 FROM camfed_attendees))`;
  }
}

async function getEventBySlug(slug) {
  const rows = await getSql()`SELECT id, name, event_date AS date, venue, slug, created_at, registration_hours, registration_expires_at FROM camfed_events WHERE slug = ${slug} LIMIT 1`;
  return numberIds(rows[0]);
}
async function getEventById(id, province) {
  const rows = province
    ? await getSql()`SELECT id, name, event_date AS date, venue, slug, created_at, registration_hours, registration_expires_at, province FROM camfed_events WHERE id = ${Number(id)} AND province = ${province} LIMIT 1`
    : await getSql()`SELECT id, name, event_date AS date, venue, slug, created_at, registration_hours, registration_expires_at, province FROM camfed_events WHERE id = ${Number(id)} LIMIT 1`;
  return numberIds(rows[0]);
}
async function getLatestEvent() {
  const rows = await getSql()`SELECT id, name, event_date AS date, venue, slug, created_at, registration_hours, registration_expires_at FROM camfed_events ORDER BY id DESC LIMIT 1`;
  return numberIds(rows[0]);
}
async function listEvents(province) {
  const rows = province
    ? await getSql()`SELECT e.id, e.name, e.event_date AS date, e.venue, e.slug, e.created_at, e.registration_hours, e.registration_expires_at, e.province, count(a.id)::int AS attendee_count FROM camfed_events e LEFT JOIN camfed_attendees a ON a.event_id = e.id WHERE e.province = ${province} GROUP BY e.id ORDER BY e.id DESC`
    : await getSql()`SELECT e.id, e.name, e.event_date AS date, e.venue, e.slug, e.created_at, e.registration_hours, e.registration_expires_at, e.province, count(a.id)::int AS attendee_count FROM camfed_events e LEFT JOIN camfed_attendees a ON a.event_id = e.id GROUP BY e.id ORDER BY e.id DESC`;
  return rows.map(numberIds);
}
async function listEventSlugs() {
  return (await getSql()`SELECT slug FROM camfed_events`).map(row => row.slug);
}
async function listAttendeesForEvent(eventId) {
  const rows = await getSql()`SELECT * FROM camfed_attendees WHERE event_id = ${Number(eventId)} ORDER BY id`;
  return rows.map(numberIds);
}
async function getAttendeeByToken(token) {
  const rows = await getSql()`SELECT * FROM camfed_attendees WHERE confirmation_token = ${token} LIMIT 1`;
  return numberIds(rows[0]);
}
async function getAttendeeById(id) {
  const rows = await getSql()`SELECT * FROM camfed_attendees WHERE id = ${Number(id)} LIMIT 1`;
  return numberIds(rows[0]);
}
async function createEvent(event) {
  const rows = await getSql()`INSERT INTO camfed_events (name, event_date, venue, slug, created_at, registration_hours, registration_expires_at, province)
    VALUES (${event.name}, ${event.date}, ${event.venue}, ${event.slug}, ${event.created_at}, ${event.registration_hours}, ${event.registration_expires_at}, ${event.province})
    RETURNING id, name, event_date AS date, venue, slug, created_at, registration_hours, registration_expires_at, province`;
  return numberIds(rows[0]);
}
async function updateEventExpiry(id, hours, expiresAt) {
  const rows = await getSql()`UPDATE camfed_events SET registration_hours = ${hours}, registration_expires_at = ${expiresAt} WHERE id = ${Number(id)}
    RETURNING id, name, event_date AS date, venue, slug, created_at, registration_hours, registration_expires_at`;
  return numberIds(rows[0]);
}
async function deleteEvent(id) {
  const attendees = await listAttendeesForEvent(id);
  const rows = await getSql()`DELETE FROM camfed_events WHERE id = ${Number(id)} RETURNING id`;
  return rows.length ? attendees : null;
}
async function createAttendee(attendee) {
  const rows = await getSql()`INSERT INTO camfed_attendees
    (full_name, gender, designation, organisation, phone_number, nrc_number, district, mobile_registered_name, signature_file, photo_file, event_id, latitude, longitude, gps_accuracy_m, gps_captured_at, confirmation_token, created_at)
    VALUES (${attendee.full_name}, ${attendee.gender}, ${attendee.designation}, ${attendee.organisation}, ${attendee.phone_number}, ${attendee.nrc_number}, ${attendee.district}, ${attendee.mobile_registered_name}, ${attendee.signature_file}, ${attendee.photo_file}, ${attendee.event_id}, ${attendee.latitude}, ${attendee.longitude}, ${attendee.gps_accuracy_m}, ${attendee.gps_captured_at}, ${attendee.confirmation_token}, ${attendee.created_at})
    RETURNING *`;
  return numberIds(rows[0]);
}
async function deleteAttendee(id) {
  const rows = await getSql()`DELETE FROM camfed_attendees WHERE id = ${Number(id)} RETURNING *`;
  return numberIds(rows[0]);
}
async function deleteExpiredAttendees(cutoff) {
  const rows = await getSql()`DELETE FROM camfed_attendees WHERE created_at < ${cutoff.toISOString()} RETURNING *`;
  return rows.map(numberIds);
}
async function listProvincialUsers() {
  return (await getSql()`SELECT id, username, province, created_at FROM camfed_provincial_users ORDER BY province, username`).map(numberIds);
}
async function getProvincialUser(username) {
  const rows = await getSql()`SELECT * FROM camfed_provincial_users WHERE lower(username) = lower(${username}) LIMIT 1`;
  return numberIds(rows[0]);
}
async function createProvincialUser(user) {
  const rows = await getSql()`INSERT INTO camfed_provincial_users (username, password_salt, password_hash, province, created_at)
    VALUES (${user.username}, ${user.password_salt}, ${user.password_hash}, ${user.province}, ${user.created_at})
    RETURNING id, username, province, created_at`;
  return numberIds(rows[0]);
}
async function updateProvincialUser(id, user) {
  const rows = await getSql()`UPDATE camfed_provincial_users SET username = ${user.username}, province = ${user.province},
    password_salt = COALESCE(${user.password_salt || null}, password_salt), password_hash = COALESCE(${user.password_hash || null}, password_hash)
    WHERE id = ${Number(id)} RETURNING id, username, province, created_at`;
  return numberIds(rows[0]);
}
async function deleteProvincialUser(id) {
  const rows = await getSql()`DELETE FROM camfed_provincial_users WHERE id = ${Number(id)} RETURNING id`;
  return rows.length > 0;
}
async function listAdminUsers() {
  return (await getSql()`SELECT id, username, created_at FROM camfed_admin_users ORDER BY lower(username)`).map(numberIds);
}
async function getAdminUser(username) {
  const rows = await getSql()`SELECT * FROM camfed_admin_users WHERE lower(username) = lower(${username}) LIMIT 1`;
  return numberIds(rows[0]);
}
async function createAdminUser(user) {
  const rows = await getSql()`INSERT INTO camfed_admin_users (username, password_salt, password_hash, created_at)
    VALUES (${user.username}, ${user.password_salt}, ${user.password_hash}, ${user.created_at})
    RETURNING id, username, created_at`;
  return numberIds(rows[0]);
}
async function updateAdminUser(id, user) {
  const rows = await getSql()`UPDATE camfed_admin_users SET username = ${user.username}, password_salt = COALESCE(${user.password_salt || null}, password_salt), password_hash = COALESCE(${user.password_hash || null}, password_hash) WHERE id = ${Number(id)} RETURNING id, username, created_at`;
  return numberIds(rows[0]);
}
async function deleteAdminUser(id) {
  const rows = await getSql()`DELETE FROM camfed_admin_users WHERE id = ${Number(id)} RETURNING id`;
  return rows.length > 0;
}

module.exports = {
  getSql, initializeDatabase, getEventBySlug, getEventById, getLatestEvent, listEvents,
  listEventSlugs, listAttendeesForEvent, getAttendeeByToken, getAttendeeById,
  createEvent, updateEventExpiry, deleteEvent, createAttendee, deleteAttendee, deleteExpiredAttendees,
  listProvincialUsers, getProvincialUser, createProvincialUser, updateProvincialUser, deleteProvincialUser,
  listAdminUsers, getAdminUser, createAdminUser, updateAdminUser, deleteAdminUser,
};
